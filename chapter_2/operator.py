# arithmetic operators
a = 10
b = 3
c = a + b  # addition
d = a - b  # subtraction
e = a * b  # multiplication
f = a / b  # division
g = a // b  # floor division
h = a % b  # modulus
i = a ** b  # exponentiation
print(c)
print(d)
print(e)
print(f)
print(g)
print(h)
print(i)

# assignment operators
x = 5
x += 2  # equivalent to x = x + 2
x -= 1  # equivalent to x = x - 1
x *= 3  # equivalent to x = x * 3
x /= 2  # equivalent to x = x / 2
print(x)

# comparison operators
p = 10
q = 15
r = p == q  # equal to
s = p != q  # not equal to
t = p > q  # greater than
u = p < q  # less than
v = p >= q  # greater than or equal to
w = p <= q  # less than or equal to
print(r)
print(s)
print(t)
print(u)
print(v)
print(w)

# logical operators
x = True 
y = False 
z = x and y # logical AND
G = x or y  # logical OR
H = not x   # logical NOT
print(z)
print(G)
print(H)